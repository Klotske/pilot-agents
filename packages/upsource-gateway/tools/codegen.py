#!/usr/bin/env python3
"""Generate ``src/upsource_gateway/models.py`` from the Upsource RPC API dump.

Reads a machine-readable API descriptor (``api.json``) produced from the Upsource
documentation mirror and emits a Python module containing:

* one ``TypedDict`` per message/DTO;
* one ``StrEnum`` per enum (``IntEnum`` for ``RPCErrors``).

Usage::

    python tools/codegen.py [--input api.json] [--output src/upsource_gateway/models.py]

The generated file is deterministic and is committed to the repository; re-run
this script only after refreshing ``tools/api.json`` from a newer Upsource.
"""

from __future__ import annotations

import argparse
import json
import keyword
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_INPUT = HERE / "api.json"
DEFAULT_OUTPUT = HERE.parent / "src" / "upsource_gateway" / "models.py"

# Protobuf scalar -> Python type.
SCALARS = {
    "String": "str",
    "Int32": "int",
    "Int64": "int",
    "Bool": "bool",
    "Float": "float",
    "Double": "float",
    "Bytes": "bytes",
}

# Enums serialized on the wire as numeric codes (error codes) -> IntEnum;
# everything else is sent/received by name -> StrEnum.
INT_ENUMS = {"RPCErrors"}

# HTTP status used for retry decisions.
RETRY_HTTP_STATUS = {429, 500, 502, 503, 504}


def strip_package(name: str) -> str:
    """Drop the ``messages.`` / ``enums.`` prefix used at the method level."""
    return name.split(".", 1)[1] if "." in name else name


def sanitize_member(name: str) -> str:
    """Make an enum value a valid Python identifier (keywords get a ``_``)."""
    return name + "_" if keyword.iskeyword(name) else name


def type_expr(t: str, label: str) -> str:
    """Annotation text for class-based TypedDict definitions."""
    base = SCALARS.get(t, t)
    if label == "repeated":
        return f"list[{base}]"
    if label == "optional":
        return f"NotRequired[{base}]"
    return base


def value_expr(t: str, label: str) -> str:
    """Value text for functional TypedDict definitions.

    Message/enum references are emitted as string forward references so that
    the (rare) keyword-named-field DTOs do not depend on definition order.
    """
    base = SCALARS.get(t, f'"{t}"')
    if label == "repeated":
        return f"list[{base}]"
    if label == "optional":
        return f"NotRequired[{base}]"
    return base


def clean_desc(s: str | None) -> str:
    return " ".join((s or "").split())


def load(api_path: Path) -> dict:
    return json.loads(api_path.read_text(encoding="utf-8"))


def validate(data: dict, messages: dict, enums: dict) -> None:
    """Fail the build if any RPC method references an unknown type."""
    problems = []
    for service in data.get("services", {}).values():
        for method in service.get("methods", []):
            for kind in ("argumentType", "returnType"):
                t = strip_package(method[kind])
                if t not in SCALARS and t not in messages and t not in enums:
                    problems.append((method["name"], kind, t))
    if problems:
        for name, kind, t in problems:
            print(f"unresolved {kind} for method {name}: {t}", file=sys.stderr)
        raise SystemExit(1)


def render(messages: dict, enums: dict) -> str:
    out: list[str] = []
    A = out.append

    A("# AUTO-GENERATED FILE - DO NOT EDIT.")
    A("# Generated by tools/codegen.py from tools/api.json.")
    A(f"# {len(messages)} messages (TypedDict), {len(enums)} enums.")
    A("")
    A("from __future__ import annotations")
    A("")
    A("import enum")
    A("from typing import NotRequired, TypedDict")
    A("")
    A("# ------------------------------------------------------------- enums")
    A("")

    for name in sorted(enums):
        e = enums[name]
        desc = clean_desc(e.get("description"))
        if desc:
            A(f"# {desc}")
        base = "enum.IntEnum" if name in INT_ENUMS else "enum.StrEnum"
        A(f"class {name}({base}):")
        values = e.get("values") or e.get("constants") or []
        if not values:
            A("    pass")
        for v in values:
            member = sanitize_member(v["name"])
            if name in INT_ENUMS:
                A(f"    {member} = {v['number']}")
            else:
                A(f'    {member} = "{v["name"]}"')
        A("")

    A("# ---------------------------------------------------------- messages")
    A("")

    functional_names = {
        name
        for name, m in messages.items()
        if any(keyword.iskeyword(f["name"]) for f in m.get("fields", []))
    }

    for name in sorted(messages):
        m = messages[name]
        desc = clean_desc(m.get("description"))
        if desc:
            A(f"# {desc}")
        fields = m.get("fields", [])
        if name in functional_names:
            # Functional form so keyword-named keys (e.g. "from") stay valid.
            A(f'{name} = TypedDict("{name}", {{')
            for f in fields:
                fd = clean_desc(f.get("description"))
                suffix = f"  # {fd}" if fd else ""
                A(f'    "{f["name"]}": {value_expr(f["type"], f["label"])},{suffix}')
            A("})")
        else:
            A(f"class {name}(TypedDict):")
            if not fields:
                A("    pass")
            for f in fields:
                fd = clean_desc(f.get("description"))
                suffix = f"  # {fd}" if fd else ""
                A(f"    {f['name']}: {type_expr(f['type'], f['label'])}{suffix}")
        A("")

    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT, help="api.json path")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="models.py path")
    args = parser.parse_args(argv)

    data = load(args.input)
    messages = data.get("messages", {})
    enums = data.get("enums", {})
    validate(data, messages, enums)

    text = render(messages, enums)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output} ({len(messages)} messages, {len(enums)} enums)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
